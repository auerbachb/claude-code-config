"""Pin the generated launcher and its account before an approved worker starts."""

import hashlib
import json
import os
import re
import shutil
import stat
import tempfile
from dataclasses import dataclass
from pathlib import Path


GENERATED = "# GENERATED by ai-quotas-setup.sh launchers — re-run that action after adding, removing, or renaming an account; edits here are overwritten."
LAUNCHER_NAME = re.compile(r"claude-[a-z0-9]+(?:-[a-z0-9]+)*\Z")
ACCOUNT = re.compile(r"[A-Za-z0-9][A-Za-z0-9._@+-]{0,127}\Z")
SESSION = re.compile(r"[0-9a-f]{8}(?:-[0-9a-f]{4}){3}-[0-9a-f]{12}\Z")
ZSH = "/bin/zsh"
RUN_LAUNCHER = r'''
setopt noaliases
typeset -r qr_fd="$1" qr_name="$2" qr_label="$3" qr_profile="$4" qr_session="$5" qr_cli="$6"
source "/dev/fd/$qr_fd" || exit 1
exec {qr_fd}<&-
(( $+functions[$qr_name] )) || exit 1
[[ "$(whence -p -- claude)" == "$qr_cli" ]] || exit 1

# Keep the generated launcher and its title, but never let a later registry
# read switch this one invocation to a different profile.
_ai_profile_dir() {
  [[ "$1" == claude && "$2" == "$qr_label" ]] || return 1
  print -r -- "$qr_profile"
}
"$qr_name" --resume "$qr_session"
'''


def identity(info):
    return info.st_dev, info.st_ino, info.st_size, info.st_mtime_ns


def read_private(path, limit):
    path = Path(path)
    if not path.is_absolute():
        raise ValueError("private file path must be absolute")
    descriptor = os.open(path, os.O_RDONLY | os.O_NOFOLLOW | os.O_NONBLOCK)
    with os.fdopen(descriptor, "rb") as stream:
        first = os.fstat(stream.fileno())
        if (not stat.S_ISREG(first.st_mode) or first.st_uid != os.getuid()
                or stat.S_IMODE(first.st_mode) & 0o077 or first.st_size > limit):
            raise ValueError("the required local file is not private")
        raw = stream.read(limit + 1)
        if (len(raw) > limit or identity(first) != identity(os.fstat(stream.fileno()))
                or identity(first) != identity(path.lstat())):
            raise ValueError("the required local file changed")
    return raw


def trusted_cli(home):
    selected = shutil.which("claude")
    entries = {home / ".local/bin/claude", home / ".claude/local/claude",
               Path("/opt/homebrew/bin/claude"), Path("/usr/local/bin/claude"), Path("/usr/bin/claude")}
    if selected is None or Path(selected) not in entries:
        raise ValueError("a trusted local Claude executable is not available on PATH")
    return Path(selected)


@dataclass(frozen=True)
class Launcher:
    path: Path
    name: str
    label: str
    profile: str
    cli: Path
    cli_identity: tuple
    profile_identity: tuple
    contents: bytes

    @property
    def proof(self):
        value = [str(self.path), self.name, self.label, self.profile, str(self.cli),
                 self.cli_identity, self.profile_identity, hashlib.sha256(self.contents).hexdigest()]
        return hashlib.sha256(json.dumps(value, separators=(",", ":")).encode()).hexdigest()

    def argv(self, descriptor, session):
        if not SESSION.fullmatch(session):
            raise ValueError("invalid native Claude session")
        return [ZSH, "-f", "-c", RUN_LAUNCHER, "quota-resume", str(descriptor),
                self.name, self.label, self.profile, session, str(self.cli)]


def snapshot_launcher(path, name, label, profile, cli):
    if not LAUNCHER_NAME.fullmatch(name) or not ACCOUNT.fullmatch(label):
        raise ValueError("the registered launcher is invalid")
    profile_path = Path(profile)
    if not profile_path.is_absolute() or not profile_path.is_dir() or profile_path.resolve(strict=True) != profile_path:
        raise ValueError("the target profile cannot be verified")
    profile_info = profile_path.stat()
    cli = Path(cli)
    if not cli.is_absolute():
        raise ValueError("the Claude executable path is not absolute")
    actual = cli.resolve(strict=True)
    info = actual.stat()
    if (not stat.S_ISREG(info.st_mode) or info.st_uid not in {0, os.getuid()}
            or stat.S_IMODE(info.st_mode) & 0o022 or not os.access(cli, os.X_OK)):
        raise ValueError("the Claude executable is not trusted")
    path = Path(path)
    raw = read_private(path, 262144)
    lines = raw.decode().splitlines()
    prefix = f"{name}() {{ _ai_launch claude '{label}' "
    if len(lines) < 2 or lines[1] != GENERATED or sum(line.startswith(prefix) for line in lines) != 1:
        raise ValueError("run ai-quotas-setup.sh launchers and use the generated launcher file")
    return Launcher(path, name, label, str(profile_path), cli,
                    (*identity(cli.lstat()), *identity(info)), (profile_info.st_dev, profile_info.st_ino), raw)


def exec_launcher(launcher, session, cwd, directory_fd):
    """Source the verified bytes, rather than reopening a file after the check."""
    with tempfile.TemporaryFile(mode="w+b") as script:
        script.write(launcher.contents)
        script.flush()
        script.seek(0)
        os.set_inheritable(script.fileno(), True)
        current = os.stat(cwd, follow_symlinks=False)
        held = os.fstat(directory_fd)
        if (current.st_dev, current.st_ino) != (held.st_dev, held.st_ino):
            raise ValueError("the approved working directory was replaced")
        os.fchdir(directory_fd)
        os.execv(ZSH, launcher.argv(script.fileno(), session))
