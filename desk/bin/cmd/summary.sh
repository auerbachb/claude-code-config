# shellcheck shell=bash
# summary: read or cache a Review's level-1 line or level-2 summary (summary get|set ID [--level 1|2]); written once, never regenerated
#
# Sourced by desk/bin/human-queue.sh, which has already loaded lib/common.sh
# and lib/db.sh and set HQ_BIN_DIR.

# shellcheck source=../lib/items.sh
. "$HQ_BIN_DIR/lib/items.sh"
# shellcheck source=../lib/secrets.sh
. "$HQ_BIN_DIR/lib/secrets.sh"
# shellcheck source=../lib/lifecycle.sh
. "$HQ_BIN_DIR/lib/lifecycle.sh"

HQ_SUMMARY_MAX_CHARS=4000
HQ_SUMMARY_MAX_LINES=40
# The level-1 line (migration 007's CHECK caps the column at 200 too).
HQ_SUMMARY_L1_MAX_CHARS=200

cmd_usage() {
  cat <<'EOF'
human-queue.sh summary — read or cache a Review's level-1 or level-2 summary.

USAGE
  human-queue.sh summary get ID [--level 1|2]
  human-queue.sh summary set ID [--level 1|2] [--file PATH]

ARGUMENTS
  ID           a Review id, for example R-88 (r-88 is accepted). Decisions
               (D-n) have no summaries.
  --level 1|2  which summary: 2 (the default) is the twenty-line one, 1 the
               one-line one the Reviews view prints
  --file PATH  read the summary from PATH; without it, from stdin (a pipe or
               a here-document, never a terminal)

LEVELS
  Level 1, one line, is generated by the desk the first time the item is
  listed, from `pr-summary-material.sh OWNER/REPO N --level 1`, and cached
  here (items.summary_l1, migration 007). Level 2, about twenty lines, is
  generated by the desk once, from `--level 2`, and cached here
  (items.summary_l2). Neither is ever generated twice. Level 3 is the diff, a
  file, or a test: fetched live, never stored.

THE SHAPE (checked by set)
  Level 1: one line, at most 200 characters, no control characters, and
  nothing shaped like a secret:

    Reviews are pulled from GitHub, so a merged PR needs no thread to report it.

  Level 2: line 1 is one bold statement: **...**. Then numbered points
  (1. ...), for what changed functionally, the judgment calls the agent
  made, what was deferred, the tests, and the links. A point may continue on
  indented lines, and blank lines are allowed. At most 40 lines and 4000
  characters, no control characters other than tab, and nothing shaped like
  a secret.

    **Reviews are pulled from GitHub, so no thread has to cooperate.**
    1. sync-reviews adds one R-n per merged PR and per captured issue.
    2. Judgment call: the first sync needs --since.
    3. Deferred: the follow-up-issue offer lands with the desk (#1758).
    4. Tests: reviews.test.sh, reviews-cli.test.sh.
    5. Links: https://github.com/OWNER/REPO/pull/N

BEHAVIOR
  get prints the cached summary exactly. set stores it once: a second set
  with different text is refused and the stored text is kept (a cached
  summary is never regenerated); the same text again changes nothing, so a
  retry is safe. Neither records an event (a summary is not a state change),
  and caching one does not make `tick` report the item again once
  migrations 004 (level 2) and 007 (level 1) are applied. Before 007, a
  level-1 call exits 1 naming `migrate`.

OUTPUT
  get: the summary. set: the canonical item id. Nothing on stderr on success.

EXIT CODES
  0  ok (including a set of the text already stored)
  1  unexpected database failure, a store without migration 007 (level 1),
     or --file cannot be read
  4  a missing or unknown action, an invalid or Decision id, a bad --level,
     a summary not in its level's shape, stdin that is a terminal, or a
     stray argument (before any connection attempt); no item has that id,
     get of an item with no summary at that level, or set of an item that
     already has a different one (after connecting)
  5  the summary looks like a secret (before any connection attempt)
  7  database unset or unreachable (within two seconds, one line on stderr)
EOF
}

# hq__summary_check TEXT — exits 4 unless TEXT has the level-2 shape. Lines
# are walked with parameter expansion, in-process: a here-document would make
# bash 3.2 write the text to a temp file.
hq__summary_check() {
  local text="$1" rest line first="" n=0 points=0 inner
  local num_re='^[0-9]{1,2}\.[[:space:]]+[^[:space:]]' cont_re='^[[:space:]]+[^[:space:]]'
  if [ "${#text}" -gt "$HQ_SUMMARY_MAX_CHARS" ]; then
    hq_die_validation "summary set: the summary is longer than $HQ_SUMMARY_MAX_CHARS characters (level 2 is about twenty lines)"
  fi
  hq_refuse_control "summary set: the summary" "$text" newline
  rest="$text"
  while :; do
    case "$rest" in
      *$'\n'*) line="${rest%%$'\n'*}"; rest="${rest#*$'\n'}" ;;
      *) line="$rest"; rest="" ;;
    esac
    n=$((n + 1))
    if [ "$n" -gt "$HQ_SUMMARY_MAX_LINES" ]; then
      hq_die_validation "summary set: the summary is longer than $HQ_SUMMARY_MAX_LINES lines (level 2 is about twenty lines)"
    fi
    if [ "$n" -eq 1 ]; then
      first="$line"
      inner="${first#\*\*}"
      inner="${inner%\*\*}"
      case "$first" in
        \*\**\*\*) ;;
        *) inner="" ;;
      esac
      case "$inner" in
        *[![:space:]*]*) ;;
        *) hq_die_validation "summary set: line 1 must be one bold statement, **like this**" ;;
      esac
    elif [[ $line =~ $num_re ]]; then
      points=$((points + 1))
    elif [ "$points" -gt 0 ] && [[ $line =~ $cont_re ]]; then
      :
    else
      case "$line" in
        *[![:space:]]*) hq_die_validation "summary set: line $n is not a numbered point (1. ...) or an indented continuation of one" ;;
      esac
    fi
    [ -n "$rest" ] || break
  done
  if [ "$points" -eq 0 ]; then
    hq_die_validation "summary set: the bold line must be followed by numbered points (1. ...)"
  fi
}

# hq__summary_get_sql LEVEL — the column is chosen from a fixed pair, never
# from input.
hq__summary_get_sql() {
  local col="summary_l$1"
  cat <<SQL
SELECT coalesce(
         (SELECT CASE WHEN $col IS NULL THEN '!no level-$1 summary is cached for ' || id
                      ELSE $col END
            FROM items WHERE id = :'hq_id'),
         '!no item ' || :'hq_id');
SQL
}

# Write-once: the row is locked, then read again in the next statement. NULL
# takes the text; the identical text is a no-op; anything else is refused and
# the stored summary is kept. LEVEL picks the column from a fixed pair.
hq__summary_set_sql() {
  local col="summary_l$1"
  hq_sql_lock_item UPDATE
  cat <<SQL
SELECT coalesce((SELECT CASE WHEN $col IS NULL THEN 'new'
                             WHEN $col = :'hq_summary' THEN 'same'
                             ELSE 'other' END
                   FROM items WHERE id = :'hq_id'), 'none') AS hq_state \gset
WITH upd AS (
  UPDATE items SET $col = :'hq_summary'
   WHERE id = :'hq_id' AND $col IS NULL
  RETURNING id
)
SELECT CASE :'hq_state'
         WHEN 'none' THEN '!no item ' || :'hq_id'
         WHEN 'other' THEN '!' || :'hq_id' || ' already has a level-$1 summary; a cached summary is never regenerated'
         ELSE :'hq_id'
       END
  FROM (SELECT count(*) FROM upd) AS written;
SQL
}

cmd_run() {
  local action="" raw_id="" id="" file="" have_id=0 have_file=0 level=2 have_level=0 text errf out rc
  case "${1:-}" in
    -h|--help)
      cmd_usage
      exit 0
      ;;
  esac
  if [ "$#" -eq 0 ]; then
    hq_die_validation "summary: missing action: get or set (run human-queue.sh summary --help)"
  fi
  action="$1"
  shift
  case "$action" in
    get|set) ;;
    -*) hq_die_validation "summary: unknown $(hq_flag_name "$action") (run human-queue.sh summary --help)" ;;
    *) hq_die_validation "summary: unknown action (expected get or set)" ;;
  esac
  while [ "$#" -gt 0 ]; do
    case "$1" in
      -h|--help)
        cmd_usage
        exit 0
        ;;
      --file)
        if [ "$action" != set ]; then hq_die_validation "summary get: unknown option '--file'"; fi
        if [ "$have_file" -eq 1 ]; then hq_die_validation "summary set: --file given more than once"; fi
        if [ "$#" -lt 2 ]; then hq_die_validation "summary set: --file needs a path"; fi
        have_file=1
        file="$2"
        shift 2
        continue
        ;;
      --level)
        if [ "$have_level" -eq 1 ]; then hq_die_validation "summary $action: --level given more than once"; fi
        if [ "$#" -lt 2 ]; then hq_die_validation "summary $action: --level needs a value (1 or 2)"; fi
        case "$2" in
          1|2) level="$2" ;;
          *) hq_die_validation "summary $action: --level must be 1 or 2 (level 3 is never stored)" ;;
        esac
        have_level=1
        shift 2
        continue
        ;;
      -*) hq_die_validation "summary $action: unknown $(hq_flag_name "$1") (run human-queue.sh summary --help)" ;;
    esac
    if [ "$have_id" -eq 1 ]; then hq_die_validation "summary $action: takes one item id"; fi
    have_id=1
    raw_id="$1"
    shift
  done
  if [ "$have_id" -eq 0 ]; then
    hq_die_validation "summary $action: missing item id (run human-queue.sh summary --help)"
  fi
  hq_item_id id "$raw_id"
  hq_require_kind "summary $action" "$id" review

  if [ "$action" = set ]; then
    if [ "$have_file" -eq 1 ]; then
      if [ ! -f "$file" ] || [ ! -r "$file" ]; then
        hq_die_error "summary set: cannot read --file (not a readable file)"
      fi
      text=$(cat "$file") || hq_die_error "summary set: cannot read --file"
    else
      if [ -t 0 ]; then
        hq_die_validation "summary set: pipe the summary on stdin or give --file"
      fi
      text=$(cat)
    fi
    hq_trim text "$text"
    case "$text" in
      *[![:space:]]*) ;;
      *) hq_die_validation "summary set: the summary is empty" ;;
    esac
    if [ "$level" -eq 1 ]; then
      hq_check_text "summary set: the level-1 line" "$text" "$HQ_SUMMARY_L1_MAX_CHARS"
    else
      hq__summary_check "$text"
    fi
    hq_refuse_secret "summary set: the summary" "$text"
  fi

  hq_db_connect
  hq_mktemp errf
  rc=0
  if [ "$action" = get ]; then
    out=$(hq__summary_get_sql "$level" | hq_db_script -At -v "hq_id=$id" 2>"$errf") || rc=$?
  else
    out=$(hq__summary_set_sql "$level" | hq_db_script -At -v "hq_id=$id" -v "hq_summary=$text" 2>"$errf") || rc=$?
  fi
  if [ "$rc" -ne 0 ]; then
    # Level 1 lives in migration 007's column: name `migrate` when it is missing.
    hq_fail_unmigrated "$rc" "$errf" "summary $action" 'summary_l1'
  fi
  hq_problem_check "summary $action" "$out"
  if [ "$action" = set ] && [ "$out" != "$id" ]; then
    hq_die_error "summary set: the store returned no item id"
  fi
  printf '%s\n' "$out"
}
